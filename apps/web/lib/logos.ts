const DARK_TILE = new Set(["javascript", "react", "intercom", "drizzle", "webpack", "babel", "huggingface", "gitbook", "ruff", "dotenv"]);

export interface LogoRef {
  src: string;
  dark: boolean;
}

export function logoFor(name: string | null | undefined): LogoRef | null {
  if (!name) return null;
  const slug = SLUG[name.trim().toLowerCase()];
  if (!slug) return null;
  return { src: `/logos/${slug}.svg`, dark: DARK_TILE.has(slug) };
}
